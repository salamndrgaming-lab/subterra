export function generateMockProduction(wellId: string, months = 36): WellProductionMonth[] {
  const out: WellProductionMonth[] = [];
  const start = new Date('2022-01-01');
  // simple Arps hyperbolic decline starting at random IP
  const seed = wellId.charCodeAt(0) + wellId.charCodeAt(5);
  const ipOil = 18000 + (seed % 12) * 1500;
  const ipGas = 22000 + (seed % 9) * 2400;
  const di = 0.18; // initial decline
  const b = 0.9;   // hyperbolic exponent

  for (let i = 0; i < months; i++) {
    const t = i;
    const declineFactor = Math.pow(1 + b * di * t, -1 / b);
    const oil = Math.round(ipOil * declineFactor);
    const gas = Math.round(ipGas * declineFactor * 1.2);
    const water = Math.round(oil * 0.65);
    const date = new Date(start);
    date.setMonth(start.getMonth() + i);
    out.push({
      reportMonth: date.toISOString().slice(0, 10),
      oilBbl: oil,
      gasMcf: gas,
      waterBbl: water,
      daysProduced: 30,
    });
  }
  return out;
}
